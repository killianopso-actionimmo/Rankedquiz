export const JETPUNK_ROUNDS: JetpunkRound[] = CURATED_JETPUNK_ROUNDS;

export function getQuestionsByCategory(category: CategoryId): QcmQuestion[] {
  return QCM_QUESTIONS.filter((q) => q.category === category);
}

export function getRandomQuestions(count: number, category?: CategoryId, difficulty?: 1 | 2 | 3): QcmQuestion[] {
  let pool = category ? getQuestionsByCategory(category) : QCM_QUESTIONS;
  if (difficulty) {
    pool = pool.filter((q) => q.difficulty === difficulty);
  }
  const shuffled = [...pool].sort(() => Math.random() - 0.5);
  return shuffled.slice(0, count);
}

const DAILY_QUESTION_COUNT = 20;

export function getDailyQuestions(date: Date = new Date()): QcmQuestion[] {
  const dayIndex = Math.floor(date.getTime() / 86_400_000);
  const pool = QCM_QUESTIONS;
  const start = dayIndex % pool.length;
  const picked: QcmQuestion[] = [];

  for (let i = 0; i < DAILY_QUESTION_COUNT; i++) {
    picked.push(pool[(start + i * 7) % pool.length]);
  }

  return picked;
}
