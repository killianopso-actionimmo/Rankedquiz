function shuffleArray<T>(array: T[]): T[] {
  const copy = [...array];
  for (let i = copy.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [copy[i], copy[j]] = [copy[j], copy[i]];
  }
  return copy;
}

export function shuffleQuestionChoices(q: QcmQuestion): QcmQuestion {
  const indices = Array.from({ length: q.choices.length }, (_, i) => i);
  const shuffledIndices = shuffleArray(indices);
  const newAnswerIndex = shuffledIndices.indexOf(q.answerIndex);
  const newChoices = shuffledIndices.map(i => q.choices[i]) as [string, string, string, string];
  return { ...q, choices: newChoices, answerIndex: newAnswerIndex };
}

